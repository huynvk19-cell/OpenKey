#!/usr/bin/env python3
"""Generate Sources/OpenKey/engine/AutoSwitchData.h from wordfreq word lists.

English words are stored as lowercase ASCII. Vietnamese syllables are stored
as "<base letters><tone digit>" so tone placement style (hoà / hòa) does not
matter: tone 0 = none, 1 = sắc (s), 2 = huyền (f), 3 = hỏi (r), 4 = ngã (x),
5 = nặng (j).

Usage: python3 tools/gen_autoswitch_data.py > Sources/OpenKey/engine/AutoSwitchData.h
Word frequency data: wordfreq (https://github.com/rspeer/wordfreq), CC BY-SA 4.0.
"""
import re
import unicodedata

from wordfreq import top_n_list, zipf_frequency

EN_COUNT = 50000
VN_COUNT = 20000

TONE_MARKS = {"\u0301": 1, "\u0300": 2, "\u0309": 3, "\u0303": 4, "\u0323": 5}
VN_LETTERS = set("abcdefghiklmnopqrstuvxyăâđêôơư")
VN_NUCLEI = ("iêu oai oao oay oeo uây uôi uya uyê uyu ươi ươu yêu "
             "ai ao au ay âu ây eo êu ia iê iu oa oă oe oi ôi ơi ua uâ uê ui uô uơ uy ưa ưi ươ ưu yê "
             "a ă â e ê i o ô ơ u ư y").split()
VN_SYLLABLE = re.compile(
    r"(ngh|ng|nh|ch|gh|gi|kh|ph|qu|th|tr|[bcdđghklmnprstvx])?(%s)(ch|ng|nh|[cmnpt])?" % "|".join(VN_NUCLEI))


def vn_key(word):
    tone = 0
    kept = []
    for ch in unicodedata.normalize("NFD", word):
        if ch in TONE_MARKS:
            if tone:
                return None
            tone = TONE_MARKS[ch]
        else:
            kept.append(ch)
    base = unicodedata.normalize("NFC", "".join(kept))
    if not base or any(c not in VN_LETTERS for c in base) or not VN_SYLLABLE.fullmatch(base):
        return None
    return base + str(tone)


def main():
    en = {}
    for w in top_n_list("en", EN_COUNT):
        if re.fullmatch(r"[a-z]+", w) and (len(w) > 1 or w in ("a", "i")):
            en[w] = max(en.get(w, 0), round(zipf_frequency(w, "en") * 10))
    vn = {}
    for w in top_n_list("vi", VN_COUNT):
        key = vn_key(w)
        if key and len(key) <= 9:
            vn[key] = max(vn.get(key, 0), round(zipf_frequency(w, "vi") * 10))

    # Vietnamese bases without any marks (for "could this still become a word?")
    strip = str.maketrans("ăâđêôơư", "aadeoou")
    vn_plain = sorted({k[:-1].translate(strip) for k in vn})

    out = []
    out.append("// Generated by tools/gen_autoswitch_data.py - do not edit by hand.")
    out.append("// Word frequency data: wordfreq (https://github.com/rspeer/wordfreq), CC BY-SA 4.0.")
    out.append("#ifndef AutoSwitchData_h\n#define AutoSwitchData_h\n")
    out.append("struct AutoSwitchWord { const char* word; unsigned char zipf10; };\n")
    for name, table in (("kEnglishWords", en), ("kVietnameseSyllables", vn)):
        keys = sorted(table, key=lambda k: k.encode("utf-8"))
        out.append("static const AutoSwitchWord %s[] = {" % name)
        for k in keys:
            out.append('\t{"%s", %d},' % ("".join("\\x%02x" % b for b in k.encode("utf-8"))
                                          if not k.isascii() else k, table[k]))
        out.append("};")
        out.append("static const int %sCount = %d;\n" % (name, len(keys)))
    out.append("static const char* const kVietnamesePlain[] = {")
    for k in vn_plain:
        out.append('\t"%s",' % k)
    out.append("};")
    out.append("static const int kVietnamesePlainCount = %d;\n" % len(vn_plain))
    out.append("#endif")
    print("\n".join(out))


if __name__ == "__main__":
    main()
